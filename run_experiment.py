"""
Reproducible experiment: run every strategy on several markets and save the
tables + figures used in the write-up to ``results/``.

    python run_experiment.py                      # simulated + SPY, AAPL, BTC-USD
    python run_experiment.py --tickers SPY QQQ    # choose real tickers
    python run_experiment.py --cost-bps 5 --threshold 0.75
    python run_experiment.py --seeds 10           # more simulated seeds (slower)
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib
import pandas as pd

matplotlib.use("Agg")

from uncertain_trader import (  # noqa: E402
    calibration_table,
    default_strategies,
    load_prices,
    run_all,
    simulate_prices,
    threshold_sweep,
)
from uncertain_trader.backtest import build_signals  # noqa: E402
from uncertain_trader.metrics import format_table  # noqa: E402
from uncertain_trader.plots import (  # noqa: E402
    plot_calibration,
    plot_decisions,
    plot_equity,
    plot_threshold_sweep,
)

RESULTS = Path(__file__).resolve().parent / "results"


def run_market(name: str, prices: pd.DataFrame, args: argparse.Namespace, report: list[str]) -> pd.Series:
    signals = build_signals(prices)
    strategies = default_strategies(threshold=args.threshold, long_only=args.long_only)
    results, table = run_all(signals, strategies, cost_bps=args.cost_bps)
    cal = calibration_table(signals)
    sweep = threshold_sweep(signals, cost_bps=args.cost_bps, long_only=args.long_only)

    slug = name.lower().replace(" ", "_").replace("-", "_")
    table.to_csv(RESULTS / f"{slug}_summary.csv")
    sweep.to_csv(RESULTS / f"{slug}_sweep.csv")
    cal.to_csv(RESULTS / f"{slug}_calibration.csv")
    plot_equity(results, f"{name}: growth of 1.0").savefig(RESULTS / f"{slug}_equity.png")
    plot_decisions(results["Risk-Aware"], signals["close"], title=f"{name}: Risk-Aware decisions, last 250 days").savefig(
        RESULTS / f"{slug}_decisions.png"
    )
    plot_calibration(cal, f"{name}: is confidence honest?").savefig(RESULTS / f"{slug}_calibration.png")
    plot_threshold_sweep(sweep, table.loc["Always Trade", "sharpe"]).savefig(RESULTS / f"{slug}_sweep.png")
    matplotlib.pyplot.close("all")

    period = f"{signals.index[0].date()} to {signals.index[-1].date()} ({len(signals)} trading days)"
    print(f"\n=== {name}  [{period}] ===")
    print(format_table(table).to_string())
    print("\nCalibration (stated confidence vs actual accuracy):")
    print(cal.round(3).to_string())

    report.append(f"## {name}\n\nPeriod: {period}. Costs: {args.cost_bps} bps per unit traded.\n")
    report.append(format_table(table).to_markdown() + "\n")
    report.append("Calibration:\n\n" + cal.round(3).to_markdown() + "\n")
    report.append(f"![equity]({slug}_equity.png)\n![sweep]({slug}_sweep.png)\n![calibration]({slug}_calibration.png)\n")
    return table["sharpe"]


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--tickers", nargs="*", default=["SPY", "AAPL", "BTC-USD"])
    p.add_argument("--start", default="2010-01-01")
    p.add_argument("--seeds", type=int, default=3, help="number of simulated markets")
    p.add_argument("--signal-strength", type=float, default=0.30)
    p.add_argument("--cost-bps", type=float, default=5.0)
    p.add_argument("--threshold", type=float, default=0.70)
    p.add_argument("--long-only", action="store_true")
    p.add_argument("--no-real", action="store_true", help="skip real-market downloads")
    args = p.parse_args()

    RESULTS.mkdir(exist_ok=True)
    report = ["# Experiment results\n", "Generated by `run_experiment.py`.\n"]
    sharpes: dict[str, pd.Series] = {}

    for seed in range(args.seeds):
        name = f"Simulated seed {seed}"
        prices = simulate_prices(seed=seed, signal_strength=args.signal_strength)
        sharpes[name] = run_market(name, prices, args, report)

    if not args.no_real:
        for ticker in args.tickers:
            sharpes[ticker] = run_market(ticker, load_prices(ticker, start=args.start), args, report)

    overview = pd.DataFrame(sharpes).round(2)
    print("\n=== Sharpe ratio by market ===")
    print(overview.to_string())
    report.insert(2, "## Sharpe ratio by market\n\n" + overview.to_markdown() + "\n")
    (RESULTS / "REPORT.md").write_text("\n".join(report), encoding="utf-8")
    print(f"\nSaved tables, figures and REPORT.md to {RESULTS}")


if __name__ == "__main__":
    main()
